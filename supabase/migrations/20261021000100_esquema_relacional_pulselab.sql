BEGIN;

-- 1. Tabla: usuario
-- Unifica las colecciones anteriores de Firestore (users, pending_users, student_accounts)
CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_uid UUID UNIQUE, -- Vinculado a auth.users(id) cuando se usa Supabase Auth
    firebase_uid VARCHAR(128) UNIQUE, -- Para trazabilidad durante la migración desde Firebase
    nombre VARCHAR(100) NOT NULL,
    rol VARCHAR(30) NOT NULL DEFAULT 'student' CHECK (rol IN ('admin', 'student', 'user')),
    correo VARCHAR(150) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_usuario_correo ON public.usuario (correo);
CREATE INDEX IF NOT EXISTS idx_usuario_rol ON public.usuario (rol);

-- 2. Tabla: caso_clinico
-- Almacena los datos generales del caso y signos vitales base del paciente
CREATE TABLE IF NOT EXISTS public.caso_clinico (
    id_caso_clinico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_firebase_id VARCHAR(128) UNIQUE, -- ID original del documento en Firestore
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT,
    nombre_paciente VARCHAR(150),
    edad_paciente SMALLINT CHECK (edad_paciente IS NULL OR (edad_paciente >= 0 AND edad_paciente <= 150)),
    peso_paciente DECIMAL(5,2) CHECK (peso_paciente IS NULL OR peso_paciente > 0),
    talla_paciente DECIMAL(5,2) CHECK (talla_paciente IS NULL OR talla_paciente > 0),
    imc DECIMAL(4,2) CHECK (imc IS NULL OR imc > 0),
    estado VARCHAR(30) NOT NULL DEFAULT 'draft' CHECK (estado IN ('draft', 'published')),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fc INT,
    fr INT,
    spo2 INT CHECK (spo2 IS NULL OR (spo2 >= 0 AND spo2 <= 100)),
    pa_sistolica INT,
    pa_diastolica INT,
    temperatura DECIMAL(4,1),
    duracion_minutos INT CHECK (duracion_minutos IS NULL OR (duracion_minutos >= 1 AND duracion_minutos <= 180)),
    usuario_id_usuario BIGINT REFERENCES public.usuario(id_usuario) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_caso_clinico_estado ON public.caso_clinico (estado);
CREATE INDEX IF NOT EXISTS idx_caso_clinico_fecha ON public.caso_clinico (fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_caso_clinico_usuario ON public.caso_clinico (usuario_id_usuario);

-- 3. Tabla: pregunta
-- Preguntas pertenecientes a un caso clínico (relación 1:N con caso_clinico)
CREATE TABLE IF NOT EXISTS public.pregunta (
    id_pregunta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto TEXT NOT NULL,
    retroalimentacion TEXT,
    orden INT NOT NULL DEFAULT 1 CHECK (orden >= 1),
    opcion_a TEXT NOT NULL DEFAULT '',
    opcion_b TEXT NOT NULL DEFAULT '',
    opcion_c TEXT NOT NULL DEFAULT '',
    opcion_d TEXT NOT NULL DEFAULT '',
    concepto VARCHAR(150),
    opcion_correcta CHAR(1) NOT NULL DEFAULT 'a' CHECK (LOWER(opcion_correcta) IN ('a', 'b', 'c', 'd')),
    caso_clinico_id_caso_clinico BIGINT NOT NULL REFERENCES public.caso_clinico(id_caso_clinico) ON DELETE CASCADE,
    CONSTRAINT uq_pregunta_caso_orden UNIQUE (caso_clinico_id_caso_clinico, orden)
);

CREATE INDEX IF NOT EXISTS idx_pregunta_caso ON public.pregunta (caso_clinico_id_caso_clinico, orden);

-- 4. Tabla: resultado
-- Registro de un intento completado por un alumno en un caso clínico
CREATE TABLE IF NOT EXISTS public.resultado (
    id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_firebase_id VARCHAR(128) UNIQUE,
    tiempo_usado_segundos SMALLINT NOT NULL DEFAULT 0 CHECK (tiempo_usado_segundos >= 0),
    total_preguntas INT NOT NULL DEFAULT 0 CHECK (total_preguntas >= 0),
    comodin_usado BOOLEAN NOT NULL DEFAULT FALSE,
    aciertos INT NOT NULL DEFAULT 0 CHECK (aciertos >= 0),
    porcentaje DECIMAL(5,2) NOT NULL DEFAULT 0 CHECK (porcentaje >= 0 AND porcentaje <= 100),
    fecha_completado TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    usuario_id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
    caso_clinico_id_caso_clinico BIGINT NOT NULL REFERENCES public.caso_clinico(id_caso_clinico) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_resultado_usuario ON public.resultado (usuario_id_usuario);
CREATE INDEX IF NOT EXISTS idx_resultado_caso ON public.resultado (caso_clinico_id_caso_clinico);
CREATE INDEX IF NOT EXISTS idx_resultado_fecha ON public.resultado (fecha_completado DESC);

-- 5. Tabla: respuesta_alumno
-- Detalle individual de cada respuesta dada por el alumno en un intento
CREATE TABLE IF NOT EXISTS public.respuesta_alumno (
    id_respuesta_alumno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opcion_seleccionada CHAR(1) CHECK (opcion_seleccionada IS NULL OR LOWER(opcion_seleccionada) IN ('a', 'b', 'c', 'd')),
    es_correcta BOOLEAN NOT NULL DEFAULT FALSE,
    tiempo_agotado BOOLEAN NOT NULL DEFAULT FALSE,
    resultado_id_resultado BIGINT NOT NULL REFERENCES public.resultado(id_resultado) ON DELETE CASCADE,
    pregunta_id_pregunta BIGINT NOT NULL REFERENCES public.pregunta(id_pregunta) ON DELETE CASCADE,
    CONSTRAINT uq_respuesta_resultado_pregunta UNIQUE (resultado_id_resultado, pregunta_id_pregunta)
);

CREATE INDEX IF NOT EXISTS idx_respuesta_resultado ON public.respuesta_alumno (resultado_id_resultado);
CREATE INDEX IF NOT EXISTS idx_respuesta_pregunta ON public.respuesta_alumno (pregunta_id_pregunta);

COMMIT;
